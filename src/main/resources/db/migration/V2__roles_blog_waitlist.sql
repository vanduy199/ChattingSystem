-- Roles
ALTER TABLE users
    ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'USER';

ALTER TABLE users
    ADD CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN'));

-- Blog: posts
CREATE TABLE posts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug             VARCHAR(200)  NOT NULL,
    title            VARCHAR(200)  NOT NULL,
    excerpt          VARCHAR(500)  NOT NULL,
    content_markdown TEXT          NOT NULL,
    cover_image_url  VARCHAR(1000),
    meta_title       VARCHAR(70),
    meta_description VARCHAR(170),
    status           VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    published_at     TIMESTAMP WITH TIME ZONE,
    reading_minutes  INTEGER       NOT NULL DEFAULT 1,
    author_id        BIGINT        NOT NULL REFERENCES users (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_posts_slug UNIQUE (slug),
    CONSTRAINT chk_posts_status CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT chk_posts_reading_minutes CHECK (reading_minutes >= 1)
);

CREATE INDEX idx_posts_status_published_at ON posts (status, published_at DESC);
CREATE INDEX idx_posts_updated_at ON posts (updated_at DESC);
CREATE INDEX idx_posts_author_id ON posts (author_id);

-- Blog: tags
CREATE TABLE tags (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(100) NOT NULL,
    name       VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_tags_slug UNIQUE (slug)
);

CREATE TABLE post_tags (
    post_id BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    tag_id  BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (post_id, tag_id)
);

CREATE INDEX idx_post_tags_tag_id ON post_tags (tag_id);

-- Waitlist
CREATE TABLE waitlist_entries (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255) NOT NULL,
    source     VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_waitlist_entries_email UNIQUE (email)
);

CREATE INDEX idx_waitlist_entries_created_at ON waitlist_entries (created_at DESC);
